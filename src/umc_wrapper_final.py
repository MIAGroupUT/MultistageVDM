def define_roi_CC(mask : np.array,
                  **kwargs) -> Roi:

    '''
    Definition of the ROI for the common carotid, ideally it covers from the brachiocephalic trunk 
    to below C3, this should be just after the bifurcation.
    
    :param mask: Mask generated by TotalSegmentator.
    :type mask: np.array

    :return: Description
    :rtype: Roi
    '''

    use_skull = kwargs.get("use_skull", True)
    use_vertebrae = kwargs.get("use_vertebrae", True)

    roi = []

    labels = {"TRACHEA" : 16, 
              "C1" : 50,
              "C2" : 49,
              "C3" : 48,
              "C1_T2" : [50, 49, 48, 47, 46, 45, 44, 43, 42],
              "T1" : 43,
              "T2" : 42,
              "SKULL" : 91}
    
    if np.any(mask == labels["C1"]): # Just above max point of c1
        roi.append(Roi([labels["C1"]], "below", "max", dilate = 5))

    elif np.any(mask == labels["C2"]): 
        roi.append(Roi([labels["C2"]], "below", "max", dilate = 5))

    if np.any(mask == labels["SKULL"]):

            roi.append(Roi([labels["SKULL"]], "right", "max")) # Cropping to the sides.
            roi.append(Roi([labels["SKULL"]], "left", "min"))
            roi.append(Roi([labels["SKULL"]], "back", "max"))
            roi.append(Roi([labels["SKULL"]], "front", "min"))
            roi.append(Roi([labels["SKULL"]], "below", "max"))

    if not use_skull: # Keeping outside the ROI 
        roi.append(Roi([labels["SKULL"]], "outside")) # Sometimes sticks to the mandible.
            
    vertebrae_found = [np.any(mask == l) for l in labels["C1_T2"]] # We check the mask.
    roi_vertebrae = [l for v, l in zip(vertebrae_found, labels["C1_T2"]) if v] # We only keep the found ones.

    if not use_vertebrae: # Keeping the spinal column outside the ROI.
        roi.append(Roi(roi_vertebrae, "outside"))

    if np.any(mask == labels["T2"]):
        roi.append(Roi([labels["T2"]],
                       "above", "min"))
        
    else:
        for v, l in zip(vertebrae_found[::-1], labels["C1_T2"][::-1]):
            if v: 
                roi.append(Roi([l],
                           "above", "min"))    
            break
    return roi

def get_anatomical_indices(mask : np.array,
                           labels : List[int],
                           ct : sitk.Image) -> dict:
    
    indices = {}
    for label in labels: # Iteration around the provided TotalSegmentator labels.
        if np.any(mask == label):
            
            found_label = np.array(mask == label)
            indx = np.argwhere(found_label)

            idx_min = indx[np.argmin(indx[:,0])]
            idx_max = indx[np.argmax(indx[:,0])]

            indices[label] = {'max_xyz': voxel2world([int(idx_max[2]), int(idx_max[1]), int(idx_max[0])], ct),
                              'min_xyz': voxel2world([int(idx_min[2]), int(idx_min[1]), int(idx_min[0])], ct)}
    return indices

def get_stopping_criterions(params, use_circularity: bool):
    criterions = [
        RoiStoppingCriterion(params["roi"]),
        VesselDiameterStoppingCriterion(
            max_diameter=params["diameter"]["max"],
            min_diameter=params["diameter"]["min"]
        ),
    ]

    if use_circularity:
        criterions.append(
            NotAVesselStoppingCriterion(
                min_circularity=params["circularity"]["min"]
            )
        )

    return criterions

