def world2voxel(seed, ct):
    origin = np.array(ct.GetOrigin())
    spacing = np.array(ct.GetSpacing())
    direction = np.array(ct.GetDirection()).reshape(3,3)

    seed_voxel = np.linalg.inv(direction) @ (seed - origin).T
    seed_voxel = (seed_voxel.T / spacing)
    seed_voxel = np.round(seed_voxel).astype(int)

    return seed_voxel

def voxel2world(seed_voxel, ct):
    origin = np.array(ct.GetOrigin())
    spacing = np.array(ct.GetSpacing())
    direction = np.array(ct.GetDirection()).reshape(3, 3)

    seed_voxel = np.array(seed_voxel, dtype=float)
    seed_world = direction @ (seed_voxel * spacing) + origin

    return seed_world

def save_roi_file(reference_image : str, mask,
                  output_dir : str, 
                  roi : list,
                  name : str = "roi.nii.gz"):
    
    '''Saves the created ROI, if the seeds are provided as a list, 
    '''
    
    roi_array = Roi.intersection(mask, roi_list = roi)
    roi_array = roi_array.astype(np.uint8)
    
    roi_img = sitk.GetImageFromArray(roi_array)
    roi_img.CopyInformation(reference_image)
    os.makedirs(os.path.join(output_dir, "roi"), exist_ok=True)

    sitk.WriteImage(
        roi_img,
        os.path.join(output_dir, "roi", name)
    )

